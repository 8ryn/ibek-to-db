# Storage to Booster transfer

class BtsEvents(_CommonEvents):
    def __init__(self):
        super().__init__(BS_Trigger, BoosterClock, 139274)
        self.TickEvent.Append(3, 9, 10, 12, 13)

        self.DBUS(5)    # Bring both booster and machine clocks onto back
        self.DBUS(6)    # panel, as this location is transitional.
        self.OTP(3,  'TRG-CAM1',  131700, 500)    # Camera
        self.OTP(9,  'TRG-CAM2',  131700, 500)    #
        self.OTP(10, 'TRG-ADC1',  138000, 125)    # ADC trigger
        self.OTP(12, 'TRG-ICT',   138300, 125)    # ICT
        self.OTP(13, 'TRG-PMT',   124800, 125)    # PMT

        # Also generate a front panel event from SR_PRE_INJ for the
        # oscilliscope.  The delay on this event needs to track the delay
        # programmed into the power supply controller: this is used to monitor
        # the beam signal (on BS ICT-03) on the same trigger as the kicker
        # bumps.
        #    As (for unknown reasons) the tracked delay record updates
        # constantly we take care in the tracking calculation to only update
        # our own delay when it differs.
        self.EventMap('SR-PRE-INJ', self.SR_PRE_INJ, 4)
        self.OTP(4,  'SR-PRE-INJ', 0, 1250)
        self.FPS_ECL(1, 'OTP4')
        self.SetDevice()
        tracker = records.calcout('TRACK',
            CALC = 'A # B',
            OCAL = 'A',
            INPA = CP(ImportRecord('SR01S-PC-EVR-01:SET-HW').OTBD),
            INPB = self.OTP_Delay_field(4),
            OUT  = PP(self.OTP_Delay_field(4)),
            OOPT = 'When Non-zero',
            DOPT = 'Use OCAL',
            PINI = 'YES')
        self.UnsetDevice()



