# Booster

class BoosterEvents(_CommonEvents):
    def __init__(self, id):
        super().__init__(LB_Trigger, BoosterClock, 19384)

        if id == 1:
            self.BoosterOneEvents()
        elif id == 3:
            self.BoosterThreeEvents()

    def BoosterOneEvents(self):
        self.TickEvent.Append(3, 4, 9, 12, 13)
        MonitorEvent(self.EventMap('T0', self.LB0_DI_TRG, 10))

        self.DBUS(5)    # Bring Booster rev. clock onto back panel
        self.OTP(3,  'TRG-CAM1',  10000, 500)    # Camera
        self.OTP(4,  'TRG-AUX',       0, 250)    # Signal generator trigger
        self.OTP(9,  'TRG-CAM2',  12500, 500)
        self.OTP(12, 'TRG-ICT',   18350, 125)    # ICT
        self.OTP(13, 'TRG-PMT',    5000, 125)    # Beam loss monitors

        # The ADC trigger has to be very early so that the DCCT long
        # decimation filter can get a good run up (otherwise we lose the first
        # part of the signal after injection).  We do this by triggering the
        # ADC on T0 and delaying the appropriate (large) amount.  This also
        # means that the ICT readouts on the same ADC also need a large delay
        # (see BR01 ICT-03).
        #    Support in the ADC for pre-trigger readout would be helpful.
        self.OTP(10, 'TRG-ADC1',  5450000, 125)  # ADC trigger


    def BoosterThreeEvents(self):
        # The cameras in BR03C are used to monitor beam extraction, so need to
        # be triggered on the extract event.
        MonitorEvent(self.EventMap('EXTR-PRE', self.BS_DI_TRG, 3))
        self.OTP(3,  'TRG-CAM1',  131700, 500)   # Camera



