# Linac

class LinacEvents(_CommonEvents):
    def __init__(self):
        super().__init__(LB_Trigger, BoosterClock, 19384)
        self.TickEvent.Append(3, 4, 10, 12, 13)

        self.OTP(3,  'TRG-CAM1',   9934, 500)    # Camera
        self.OTP(4,  'TRG-CAM2',   9934, 500)    # Camera
        self.OTP(10, 'TRG-ADC1',  18434, 125)    # ADC trigger
        self.OTP(12, 'TRG-ICT',   18350, 125)    # ICT
        self.OTP(13, 'TRG-PMT',    4934, 125)    # Beam loss monitors


