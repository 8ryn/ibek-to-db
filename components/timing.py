# Storage Ring

class StorageEvents(_CommonEvents):
    BPM_DEFAULT_DELAY = 139274
    KICKER_DEFAULT_DELAY = 139250

    def __init__(self, cell, id=1):
        super().__init__(
            BS_Trigger, StorageClock, self.BPM_DEFAULT_DELAY, id=id)

        # Place 1MHz and machine clocks on rear panel for cells where needed
        self.DBUS(4)    # 1MHz
        self.DBUS(6)    # Storage ring machine clock

        # Generate any cell specific events
        extra_events = getattr(self, 'Storage_%02d_Events' % cell, None)
        if extra_events:
            extra_events()


    def Storage_01_Events(self):
        # Also generate camera trigger output on pre-extract event.
        self.TickEvent.Append(3, 9)
        self.OTP(3,  'TRG-CAM1',  131740, 500)    # Camera
        self.OTP(9,  'TRG-CAM2',  131740, 500)    # Camera


    def Storage_10_Events(self):
        # 10Hz chicaine trigger on back
        self.EventMap('I10-FASTCH', self.I10_FASTCH, 3)
        self.PDP(3, 'I10-FASTCH', 0, I10_CHICAINE_WIDTH, 1)
        self.FPS_ECL(1, 'PDP3')


    def Storage_23_Events(self):
        # Selectable trigger for TMBF
        self.tmbf_trigger_mode(5, self.BPM_DEFAULT_DELAY)

        # Blanking trigger for TMBF
        self.InjectEvent = self.EventMap('SR-PRE-INJ', self.SR_PRE_INJ, 9)
        self.OTP(9, 'BLANKING', 0, 125)

        # Generate kicker timing events
        for id, output in enumerate([3, 7]):
            self.pinger_trigger_mode(id, output, self.KICKER_DEFAULT_DELAY)


    # Multiplexor to select TMBF trigger.  The options are:
    #   SR-DI-TRG   (one shot trigger)
    #   BS-DI-TRG   (diagnostics 5Hz trigger)
    def tmbf_trigger_mode(self, output, default_delay):
        self.SetDevice()
        self.OTP(output, 'TMBF', default_delay, 125)

        tickEvent    = self.TickEvent.Enable_field(output)      # BS-DI
        triggerEvent = self.TriggerEvent.Enable_field(output)   # SR-DI

        selectOneShot = records.seq('TMBF:TRIG:SINGLE',
            SELM = 'All',
            DOL1 = 0,   LNK1 = PP(tickEvent),
            DOL2 = 1,   LNK2 = PP(triggerEvent))
        select5Hz = records.seq('TMBF:TRIG:5HZ',
            SELM = 'All',
            DOL1 = 0,   LNK1 = PP(triggerEvent),
            DOL2 = 1,   LNK2 = PP(tickEvent))

        modeSelection = records.mbbo('TMBF:TRIG:MODE',
            OMSL = 'supervisory',
            VAL  = 2,   PINI = 'YES',
            ONVL = 1,   ONST = 'One Shot: SR-DI',
            TWVL = 2,   TWST = 'Tick 5Hz: BS-DI')
        selectMode = records.fanout('TMBF:TRIG:SEL',
            SELM = 'Specified',
            SELL = modeSelection,
            LNK1 = selectOneShot,
            LNK2 = select5Hz)
        modeSelection.FLNK = selectMode
        UnsetDevice()


    # Multiplexor to select pinger trigger.  The options are:
    #   SR-DI-TRG   (one shot trigger)
    #   BS-DI-TRG   (diagnostics 5Hz trigger)
    #   10HZ-DIAG   (also called BEAM_LOSS for historical reasons)
    #   SR-PRE-INJ  (storage ring injection event)
    def pinger_trigger_mode(self, id, output, default_delay):
        self.SetDevice()
        # Add the requested output to the pre-extract trigger and
        # configure it, but leave it disabled by default.
        self.OTP(output, 'PINGER%d' % (id + 1),
            default_delay, 125, enabled = False)

        tickEvent    = self.TickEvent.Enable_field(output)      # BS-DI
        triggerEvent = self.TriggerEvent.Enable_field(output)   # SR-DI
        extraTrigger = self.ExtraTrigger.Enable_field(output)   # 10HZ-DIAG
        injectTrigger = self.InjectEvent.Enable_field(output)   # SR-PRE-INJ

        # The pinger trigger is selected from one of four independent
        # inputs, similar to the TRIG:MODE selection.  Note that we disable all
        # other sources before enabling our selected target to avoid a spurious
        # double trigger.
        selectOneShot = records.seq('PING%d:TRIG:SINGLE' % (id + 1),
            SELM = 'All',
            DOL1 = 0,   LNK1 = PP(tickEvent),
            DOL2 = 0,   LNK2 = PP(extraTrigger),
            DOL3 = 0,   LNK3 = PP(injectTrigger),
            DOL4 = 1,   LNK4 = PP(triggerEvent))
        select5Hz = records.seq('PING%d:TRIG:5HZ' % (id + 1),
            SELM = 'All',
            DOL1 = 0,   LNK1 = PP(triggerEvent),
            DOL2 = 0,   LNK2 = PP(extraTrigger),
            DOL3 = 0,   LNK3 = PP(injectTrigger),
            DOL4 = 1,   LNK4 = PP(tickEvent))
        select10Hz = records.seq('PING%d:TRIG:10HZ' % (id + 1),
            SELM = 'All',
            DOL1 = 0,   LNK1 = PP(tickEvent),
            DOL2 = 0,   LNK2 = PP(triggerEvent),
            DOL3 = 0,   LNK3 = PP(injectTrigger),
            DOL4 = 1,   LNK4 = PP(extraTrigger))
        selectInject = records.seq('PING%d:TRIG:PRE-INJ' % (id + 1),
            SELM = 'All',
            DOL1 = 0,   LNK1 = PP(tickEvent),
            DOL2 = 0,   LNK2 = PP(triggerEvent),
            DOL3 = 0,   LNK3 = PP(extraTrigger),
            DOL4 = 1,   LNK4 = PP(injectTrigger))

        modeSelection = records.mbbo('PING%d:TRIG:MODE' % (id + 1),
            OMSL = 'supervisory',
            VAL  = 1,
            ONVL = 1,   ONST = 'One Shot: SR-DI',
            TWVL = 2,   TWST = 'Tick 5Hz: BS-DI',
            THVL = 3,   THST = 'Fast 10Hz',
            FRVL = 4,   FRST = 'SR-PRE-INJ')
        selectMode = records.fanout('PING%d:TRIG:SEL' % (id + 1),
            SELM = 'Specified',
            SELL = modeSelection,
            LNK1 = selectOneShot,
            LNK2 = select5Hz,
            LNK3 = select10Hz,
            LNK4 = selectInject)
        modeSelection.FLNK = selectMode
        UnsetDevice()
